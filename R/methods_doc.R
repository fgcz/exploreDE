#' detect_read_count_column
#' The sample-table column holding each library's read count: an exact name
#' (`Reads`, `Read_Count`, `Raw_Reads`, `Total_Reads`) first, then a name with
#' "Read" and "Count", then one with "Read" that is not a file, name, mapped,
#' aligned, gene or feature column.
#' @param cols Column names of the sample table.
#' @return The column name, or `NULL`.
#' @noRd
detect_read_count_column <- function(cols) {
  exact <- grep("^Read_?Count$|^Reads$|^Raw_?Reads$|^Total_?Reads$", cols, value = TRUE, ignore.case = TRUE)
  read_count <- grep("Count", grep("Read", cols, value = TRUE, ignore.case = TRUE), value = TRUE, ignore.case = TRUE)
  read_count <- grep("File|Path|Name", read_count, value = TRUE, invert = TRUE, ignore.case = TRUE)
  read_any <- grep(
    "File|Path|Name|Mapped|Gene|Feature|Aligned",
    grep("Read", cols, value = TRUE, ignore.case = TRUE),
    value = TRUE,
    invert = TRUE,
    ignore.case = TRUE
  )
  hit <- c(exact, read_count, read_any)
  if (length(hit)) hit[1] else NULL
}

#' library_size_text
#' The library-size sentence of the Methods text, from the sample table's
#' read-count column.
#' @param dataset Sample table (`eds$samples()`).
#' @return The sentence, or `""` when there is no numeric read-count column.
#' @noRd
library_size_text <- function(dataset) {
  col <- detect_read_count_column(colnames(dataset))
  if (is.null(col)) {
    return("")
  }
  reads <- eds_as_numeric(as.character(dataset[[col]]))
  if (all(is.na(reads))) {
    return("")
  }
  paste0(
    "Individual library size ranged from ",
    round(min(reads, na.rm = TRUE) / 1e6, 1),
    " million to ",
    round(max(reads, na.rm = TRUE) / 1e6, 1),
    " million reads. "
  )
}

#' build_methods_docx
#' The Methods `.docx`: notice, library preparation placeholder, the analysis
#' sections from [generateMethodsText()], and the references.
#' @param sections List from `generateMethodsText()`: `data_processing`,
#'   `trimming`, `mapping`, `de_analysis`, and `go_analysis` (`NULL` when GO
#'   was not run).
#' @param citations Named list of citation strings.
#' @param date Date printed in the notice.
#' @return An `rdocx` object; write it with `print(doc, target = file)`.
#' @noRd
build_methods_docx <- function(sections, citations, date = Sys.Date()) {
  heading <- function(doc, text, size) {
    officer::body_add_fpar(
      doc,
      officer::fpar(officer::ftext(text, prop = officer::fp_text(bold = TRUE, font.size = size)))
    )
  }
  section <- function(doc, title, text) {
    doc <- heading(doc, title, 12)
    doc <- officer::body_add_par(doc, text)
    officer::body_add_par(doc, "")
  }
  doc <- officer::read_docx()
  doc <- officer::body_add_par(heading(doc, "Methods", 16), "")
  doc <- heading(doc, "IMPORTANT NOTICE", 14)
  doc <- officer::body_add_par(
    doc,
    paste0(
      "This methods section was automatically generated by the exploreDE Shiny application (beta version). ",
      "All information contained herein MUST be carefully reviewed and verified for accuracy before inclusion in any ",
      "publication or report. ",
      "Please verify: (1) all software versions are correct, (2) all analysis parameters match your study design, ",
      "(3) all citations are complete and properly formatted, and (4) the description accurately reflects your ",
      "experimental procedures. ",
      "If you have any questions or concerns, please consult with your bioinformatics coach or contact the FGCZ team ",
      "at sequencing@fgcz.ethz.ch. ",
      "Generated on: ",
      format(date, "%d %B %Y"),
      "."
    )
  )
  doc <- officer::body_add_par(doc, "")
  doc <- heading(doc, "Library Preparation", 14)
  doc <- officer::body_add_par(
    doc,
    paste0(
      "[User to complete: Include RNA quality assessment methods (Qubit, Fragment Analyzer, RIN values), library ",
      "preparation kit details, and final library normalisation procedures.]"
    )
  )
  doc <- officer::body_add_par(doc, "")
  doc <- officer::body_add_par(heading(doc, "RNA-Seq Data Analysis", 14), "")
  doc <- section(doc, "Data Processing", sections$data_processing)
  doc <- section(doc, "Read Trimming and Quality Control", sections$trimming)
  doc <- section(doc, "Read Mapping and Quantification", sections$mapping)
  doc <- section(doc, "Differential Expression Analysis", sections$de_analysis)
  if (!is.null(sections$go_analysis)) {
    doc <- section(doc, "Gene Ontology Enrichment Analysis", sections$go_analysis)
  }
  doc <- officer::body_add_par(heading(doc, "References", 14), "")
  for (citation in citations) {
    doc <- officer::body_add_par(officer::body_add_par(doc, citation), "")
  }
  doc
}
